create table public.market_offers (
  id uuid default gen_random_uuid() primary key,
  target_id uuid references public.crawler_targets(id) on delete set null,
  product_title text not null,
  price numeric,
  status public.offer_status default 'in_stock'::public.offer_status not null,
  url text default ''::text not null,
  tags text[] default '{}'::text[] not null,
  inventory_level integer,
  scraped_at timestamptz default now() not null,
  created_at timestamptz default now() not null,
  updated_at timestamptz default now() not null,
  canonical_product_id uuid references public.product_catalog(id) on delete set null,
  is_manual_override boolean default false,
  last_crawled_at timestamptz,
  constraint unique_target_product unique (target_id, product_title)
);

