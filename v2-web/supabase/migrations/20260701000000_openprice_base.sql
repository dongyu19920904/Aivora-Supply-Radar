create type public.offer_status as enum (
  'in_stock',
  'out_of_stock',
  'offline',
  'blacklisted'
);

create function public.protect_manual_offer_override() returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if old.is_manual_override = true
     and new.last_crawled_at is distinct from old.last_crawled_at then
    new.status = old.status;
    new.canonical_product_id = old.canonical_product_id;
    new.is_manual_override = true;
  end if;
  return new;
end;
$$;

